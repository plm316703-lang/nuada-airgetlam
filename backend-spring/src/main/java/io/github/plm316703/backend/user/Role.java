package io.github.plm316703.backend.user;

/**
 * 회원의 역할(권한 종류).
 *
 * enum(열거형)을 쓰는 이유:
 *  - 문자열("PATIENT")로 관리하면 "PATEINT" 같은 오타가 들어가도 컴파일러가 못 잡아냄
 *  - enum은 정해진 값 외에는 들어갈 수 없어서 오타를 컴파일 단계에서 막아줌
 *
 * 역할 6개 (프로젝트 개요 문서의 결정):
 *  - 볼 수 있는 범위가 역할마다 다르다 → 보안 5겹 중 "역할별 권한"
 */
public enum Role{
    PATIENT,                //환자 : 로봇팔을 직접 조작하는 사용자, 본인 동의·철회
    GUARDIAN,               //보호자 : 연결된 환자의 상태 확인 (대리 동의는 발표 이후)
    RESEARCHER,             //연구자 : 배정된 환자는 실명, 나머지는 익명 코드로 열람
    PRINCIPAL_INVESTIGATOR, //연구책임자(의사) : 연구 등록, 연구자 배정, 세션 시작·재개
    OPERATOR,               //관제 담당자 : 모니터링 + 세션 시작·재개. 익명 코드만 열람
    SYSTEM_ADMIN            //시스템 관리자 : 계정 관리만
}
